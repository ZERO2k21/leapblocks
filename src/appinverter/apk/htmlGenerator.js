// ── Helpers ────────────────────────────────────────────────────────────────

function toJsIdentifier(value, fallback = 'item') {
  const raw = String(value || fallback);
  const normalized = raw.replace(/[^a-zA-Z0-9_$]/g, '_');
  return /^[a-zA-Z_$]/.test(normalized) ? normalized : `_${normalized}`;
}

function screenRendererName(screenId) {
  return `render_${toJsIdentifier(screenId, 'Screen')}`;
}

function isValidJsIdentifier(value) {
  return /^[A-Za-z_$][0-9A-Za-z_$]*$/.test(String(value || ''));
}

function validateComponentIdentifiers(screens) {
  const invalid = [];
  screens.forEach(screen => {
    const allComponents = [...(screen.components || []), ...(screen.nonVisibleComponents || [])];
    walkComponentTree(allComponents, comp => {
      if (!isValidJsIdentifier(comp.id)) invalid.push(comp.id);
    });
  });

  if (invalid.length) {
    throw new Error(`Invalid component name(s) for APK build: ${invalid.join(', ')}. Use names like Button1 without spaces or symbols.`);
  }
}

function validateGeneratedJavaScript(js) {
  try {
    // Build-time validation prevents shipping APKs that open to a blank WebView.
    new Function(js);
  } catch (error) {
    throw new Error(`Generated app JavaScript is invalid: ${error.message}`);
  }
}

function cssIdSelector(id) {
  return `#${String(id).replace(/[^a-zA-Z0-9_-]/g, (char) => `\\${char}`)}`;
}

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

function indentMultiline(value, spaces = 2) {
  const pad = ' '.repeat(Math.max(0, spaces));
  if (!value) return '';
  return String(value)
    .split('\n')
    .map((line) => (line ? pad + line : line))
    .join('\n');
}

function walkComponentTree(list, visitor) {
  if (!list) return;
  for (const item of list) {
    visitor(item);
    if (item.children?.length) walkComponentTree(item.children, visitor);
  }
}

function resolveDimension(value, fallback) {
  const normalized = typeof value === 'string' ? value.trim().toLowerCase().replace(/\s+/g, '_') : value;
  if (normalized === 'fill_parent' || normalized === 'fill_parent...' || value === -2) return '100%';
  if (normalized === 'automatic' || value === -1 || value === undefined || value === null || value === '') return fallback || 'auto';
  if (typeof value === 'number') return value + 'px';
  return value;
}

function generateComponentCss(comp) {
  const { id, type, props = {} } = comp;
  const selector = cssIdSelector('comp-' + id);
  let rules = '';

  const width = resolveDimension(props.width || props.Width, 'auto');
  const height = resolveDimension(props.height || props.Height, 'auto');

  // Resolve defaults based on component type
  let defaultBg = 'transparent';
  let defaultTextColor = '';
  
  if (['Button', 'ListPicker', 'DatePicker', 'TimePicker', 'ImagePicker', 'FilePicker', 'ContactPicker', 'EmailPicker', 'PhoneNumberPicker'].includes(type)) {
    defaultBg = '#3B82F6';
    defaultTextColor = '#ffffff';
  } else if (type === 'ListView') {
    defaultBg = '#000000';
    defaultTextColor = '#ffffff';
  } else if (['Label', 'CheckBox', 'Switch'].includes(type)) {
    defaultBg = 'transparent';
    defaultTextColor = '#000000';
  } else if (['TextBox', 'PasswordTextBox', 'Spinner'].includes(type)) {
    defaultBg = '#ffffff';
    defaultTextColor = '#000000';
  }

  const bgColor = props.backgroundColor || props.BackgroundColor || defaultBg;
  const textColor = props.textColor || props.TextColor || defaultTextColor;
  const fontSize = props.fontSize || props.FontSize || 14;
  const bold = props.bold || props.FontBold;
  const italic = props.italic || props.FontItalic;
  const padding = props.padding || 8;
  const margin = props.margin || 4;
  
  // Fix operator precedence issue
  const borderRadius = props.borderRadius !== undefined ? props.borderRadius : (props.Shape === 'rounded' ? 8 : 0);

  rules += `${selector} {\n`;
  if (width !== 'auto') rules += `  width: ${width};\n`;
  if (height !== 'auto') rules += `  height: ${height};\n`;
  if (bgColor !== 'transparent') rules += `  background-color: ${bgColor};\n`;
  if (textColor) rules += `  color: ${textColor};\n`;
  rules += `  font-size: ${fontSize}px;\n`;
  if (bold) rules += `  font-weight: bold;\n`;
  if (italic) rules += `  font-style: italic;\n`;
  rules += `  padding: ${padding}px;\n`;
  rules += `  margin: ${margin}px;\n`;
  if (borderRadius) rules += `  border-radius: ${borderRadius}px;\n`;
  rules += `}\n`;

  return rules;
}

function generateScreenRenderer(screen) {
  const screenId = screen.id;
  const components = screen.components || [];
  const renderName = screenRendererName(screenId);

  let js = `  function ${renderName}() {\n`;
  js += `    var container = document.createElement('div');\n`;
  js += `    container.id = ${JSON.stringify('screen-' + screenId)};\n`;
  js += `    container.className = 'screen';\n`;

  components.forEach(comp => {
    js += generateComponentCreation(comp, 'container');
  });

  js += `    document.getElementById('app-root').appendChild(container);\n`;
  js += `  }\n\n`;

  return js;
}

